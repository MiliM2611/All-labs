group1 = ["Фомина", "Утгов", "Роева", "Радушинская", "Подвицкий",
          "Маркевич", "Ключников", "Василенко", "Анапреенко", "Мурашова"]

group2 = ["Фёдоров", "Иванов", "Алексеев", "Орлов", "Макаров",
          "Захаров", "Павлов", "Королёв", "Лебедев", "Новиков"]

team = tuple(group1[:5] + group2[:5])

print("Первая группа:", ", ".join(group1))
print("Вторая группа:", ", ".join(group2))
print("Команда:", ", ".join(team))

print("Длина команды:", len(team))

sortedTeam = tuple(sorted(team))
print("Команда по алфавиту:", ", ".join(sortedTeam))

if "Иванов" in team:
    print("Иванов входит в команду и встречается", team.count("Иванов"), "раз")
